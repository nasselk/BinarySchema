import { describe, expect, test } from "bun:test";

import { existsSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";

import { tmpdir } from "node:os";

import { join } from "node:path";

import { field, generate } from "../src/index.js";

import { checkVersion } from "../src/runtime.js";

import { VERSION } from "../src/version.js";

describe("generate", () => {
	test("names the version and the schema file in the header and the version check", () => {
		const code = generate({ A: { fields: { a: field.uint8() } } }, { source: "game/schema.ts" });

		expect(code).toStartWith(`// Generated by BinarySchema ${VERSION} from game/schema.ts.`);
		expect(code).toContain(`checkVersion("${VERSION}", "game/schema.ts");`);
	});

	test("imports only the helpers it uses, from the runtime", () => {
		const numbers = generate({ A: { fields: { a: field.uint8() } } });
		const strings = generate({ A: { fields: { a: field.string(), b: field.float16() } } });

		expect(numbers).toContain('import { checkVersion, scratchWriter, scratchBytes, type BufferReader, type BufferWriter } from "@nasselk/binaryschema/runtime";');
		expect(strings).toContain("writeUtf8, readUtf8, float16Array");
		expect(numbers).not.toContain("F16");
		expect(generate({ A: { fields: {} } }, { runtime: "./runtime.js" })).toContain('from "./runtime.js"');
	});

	test("exports the types by name and the schemas as default", () => {
		const code = generate({ Player: { fields: { id: field.uint16({ default: 1 }) } } });

		expect(code).toContain("export type Player = {");
		expect(code).toContain("export type PlayerInput = {");
		expect(code).toContain("id?: number | undefined;");
		expect(code).toContain("Player: { minByteLength: 2, maxByteLength: 2, encode: encodePlayer, decode: decodePlayer },");
	});

	test("does not modify the schemas passed in", () => {
		const schemas = {
			Thing: {
				fields: {
					value: field.uint16({ dependencies: ["enabled"] }),
					label: field.string(),
					enabled: field.boolean(),
					inner: field.object({ text: field.string() }),
				},
				metadata: { prefix: [1] },
			},
		};

		generate(schemas);

		// Field order and defaults stay as written; nothing gets attached
		expect(Object.keys(schemas.Thing.fields)).toEqual(["value", "label", "enabled", "inner"]);
		expect("includeSize" in schemas.Thing.fields.label).toBe(false);
		expect("includeSize" in schemas.Thing.fields.inner.fields.text).toBe(false);
		expect(Object.keys(schemas.Thing)).toEqual(["fields", "metadata"]);
	});

	test("field names that need quoting or would break comments are written safely", () => {
		const code = generate({ A: { fields: { 'say "hi"': field.uint8({ max: 3 }), "line\nbreak": field.boolean() } } });

		expect(code).toContain('"say \\"hi\\"": number;');
		expect(code).toContain("// line break");
		expect(code).toContain("Field 'say \\\"hi\\\"' is out of range");
	});
});

describe("runtime", () => {
	test("checkVersion accepts its own version and explains how to fix a mismatch", () => {
		expect(() => checkVersion(VERSION, "schema.ts")).not.toThrow();
		expect(() => checkVersion("0.0.1", "game/schema.ts")).toThrow(`The file generated from game/schema.ts was made by BinarySchema 0.0.1, but ${VERSION} is installed: run \`binaryschema game/schema.ts\` again`);
	});

	test("VERSION matches package.json", async () => {
		expect(VERSION).toBe((await import("../package.json")).version);
	});
});

describe("binaryschema CLI", () => {
	const cli = join(import.meta.dir, "../src/cli.ts");
	const index = join(import.meta.dir, "../src/index.ts").replace(/\\/g, "/");

	function run(directory: string, ...args: string[]) {
		const result = Bun.spawnSync(["bun", cli, ...args], { cwd: directory });

		return { code: result.exitCode, out: result.stdout.toString(), err: result.stderr.toString() };
	}

	function withSchemaFile(content: string, check: (directory: string) => void) {
		const directory = mkdtempSync(join(tmpdir(), "binaryschema-"));

		try {
			writeFileSync(join(directory, "game.ts"), content);
			check(directory);
		} finally {
			rmSync(directory, { recursive: true, force: true });
		}
	}

	const schemaFile = `import { field } from "${index}";\nexport default { Ping: { fields: { id: field.uint8() } } };\n`;

	test("writes <name>.gen.ts next to the schema file by default", () => {
		withSchemaFile(schemaFile, (directory) => {
			const result = run(directory, "game.ts");

			expect(result.code).toBe(0);
			expect(result.out).toContain("Generated game.gen.ts (1 schema)");

			const code = readFileSync(join(directory, "game.gen.ts"), "utf8");
			expect(code).toContain("// Generated by BinarySchema");
			expect(code).toContain('from "@nasselk/binaryschema/runtime"');
			expect(code).toContain('checkVersion("0.1.0", "game.ts");');
		});
	});

	test("-o and --runtime choose the output file and the runtime module", () => {
		withSchemaFile(schemaFile, (directory) => {
			expect(run(directory, "game.ts", "-o", "out/codec.ts", "--runtime", "my-runtime").code).toBe(1); // the folder doesn't exist
			expect(run(directory, "game.ts", "-o", "codec.ts", "--runtime", "my-runtime").code).toBe(0);
			expect(existsSync(join(directory, "game.gen.ts"))).toBe(false);
			expect(readFileSync(join(directory, "codec.ts"), "utf8")).toContain('from "my-runtime"');
		});
	});

	test("explains what's wrong instead of crashing", () => {
		withSchemaFile("export const nothing = 1;\n", (directory) => {
			const result = run(directory, "game.ts");

			expect(result.code).toBe(1);
			expect(result.err).toContain("game.ts has no default export");
		});

		withSchemaFile(schemaFile, (directory) => {
			expect(run(directory).err).toContain("Usage: binaryschema <schema.ts>");
			expect(run(directory, "game.ts", "--nope").err).toContain("Unexpected argument: --nope");
			expect(run(directory, "game.ts", "-o", "game.ts").err).toContain("can't be the schema file itself");
		});
	});
});
